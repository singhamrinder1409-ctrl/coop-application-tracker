CREATE TABLE ApplicationResume (
    application_id INT PRIMARY KEY,
    resume_id INT NOT NULL,
    FOREIGN KEY (application_id) REFERENCES Application(application_id),
    FOREIGN KEY (resume_id) REFERENCES ResumeVersion(resume_id)
) ENGINE=InnoDB;

INSERT INTO ApplicationResume(application_id,resume_id)
SELECT application_id,resume_id FROM Application WHERE resume_id IS NOT NULL;
-- This FK name is the one generated by the exact archived kick-off DDL.
ALTER TABLE Application DROP FOREIGN KEY Application_ibfk_4;
ALTER TABLE Application DROP COLUMN resume_id;
ALTER TABLE Application MODIFY priority INT NOT NULL DEFAULT 3;
